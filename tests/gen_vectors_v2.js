/* Generates conformance vectors for protocol v2 from src/devicesig.js.
   usage: node tests/gen_vectors_v2.js <out.json> [<out.h>]
   The C host test in ADC_100_Controller (tests/host) verifies them with the real
   firmware code, so dashboard and firmware cannot silently drift apart. */
process.env.DEVICE_MASTER_KEY = 'conformance-master-key-0123456789abcdef-0123456789';
const fs = require('fs');
const sig = require('../src/devicesig');

const dev = { mqtt_id: 'Fady_Door_A', serial: 'ADC-0001', key_version: 2 };
const other = { mqtt_id: 'Other_Door', serial: 'ADC-0002', key_version: 2 };
const ts = 1760000000;
const nonce = (i) => i.toString(16).padStart(16, '0');

const cases = [];
let i = 1;
function add(name, device, cmd, fields, expectOk, mutate) {
    const payload = sig.buildCommand(device, cmd, fields, { ts, nonce: nonce(i++) });
    let json = JSON.stringify(payload);
    if (mutate) json = mutate(json, payload);
    cases.push({ name, device_id: dev.mqtt_id, cmd, ts, hmac: payload.hmac, json, expect: expectOk });
}

add('open timed', dev, 'open', { relay_mode: 'timed', relay_duration: 5 }, true);
add('open latched', dev, 'open', { relay_mode: 'latched' }, true);
add('get_logs', dev, 'get_logs', {}, true);
add('restart', dev, 'restart', {}, true);
add('add rfid', dev, 'add_credential', { cred_type: 'rfid', cred_data: 'AABBCCDD', label: 'Card 1', duress: 'false' }, true);
add('add pin with tricky label', dev, 'add_credential', { cred_type: 'pin', cred_data: '1234', label: 'Zoë "Z" | a\\b\nc', duress: 'false' }, true);
add('delete credential', dev, 'delete_credential', { label: 'Card 1' }, true);
add('set_schedule', dev, 'set_schedule', { enabled: 'true', start: '08:00', end: '17:30' }, true);
add('set_wifi', dev, 'set_wifi', { ssid: 'My "Net"', pass: 'p@ss|word\\1' }, true);
add('ota_update', dev, 'ota_update', { url: 'https://example.com/fw/adc100.bin' }, true);
add('set_ble_name', dev, 'set_ble_name', { name: 'ADC100-LOBBY' }, true);

/* attacks: all must be rejected */
add('ATTACK: ota url swapped after signing', dev, 'ota_update', { url: 'https://example.com/fw/adc100.bin' }, false,
    (j) => j.replace('example.com', 'evil.example'));
add('ATTACK: relay_duration changed', dev, 'open', { relay_mode: 'timed', relay_duration: 5 }, false,
    (j) => j.replace('"relay_duration":5', '"relay_duration":300'));
add('ATTACK: credential data changed', dev, 'add_credential', { cred_type: 'pin', cred_data: '1234', label: 'x', duress: 'false' }, false,
    (j) => j.replace('"cred_data":"1234"', '"cred_data":"9999"'));
add('ATTACK: signed for another door', other, 'open', { relay_mode: 'timed', relay_duration: 5 }, false);
add('ATTACK: v1-style signature (cmd:ts)', dev, 'open', { relay_mode: 'timed', relay_duration: 5 }, false,
    (j, p) => j.replace(p.hmac, require('crypto').createHmac('sha256', 'x').update(`open:${ts}`).digest('hex')));
add('ATTACK: nonce changed', dev, 'get_logs', {}, false, (j, p) => j.replace(p.n, 'ffffffffffffffff'));
add('ATTACK: missing field becomes empty', dev, 'delete_credential', { label: 'Card 1' }, false,
    (j) => j.replace('"label":"Card 1",', ''));

const qrIat = 1760000000, qrExp = 1760003600;
const out = {
    device_id: dev.mqtt_id,
    device_key_hex: sig.deviceKey(dev).toString('hex'),
    ble_key_hex: sig.bleKey(dev).toString('hex'),
    qr_ok: sig.temporaryQr(dev, qrIat, qrExp),
    qr_other_door: sig.temporaryQr(other, qrIat, qrExp),
    cases
};
fs.writeFileSync(process.argv[2], JSON.stringify(out, null, 2));

if (process.argv[3]) {
    const cstr = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';
    let h = '/* GENERATED by dashboard tests/gen_vectors_v2.js — do not edit */\n#pragma once\n';
    h += `#define VEC_DEVICE_ID ${cstr(out.device_id)}\n#define VEC_DEVKEY_HEX ${cstr(out.device_key_hex)}\n#define VEC_BLEKEY_HEX ${cstr(out.ble_key_hex)}\n`;
    h += `#define VEC_QR_OK ${cstr(out.qr_ok)}\n#define VEC_QR_OTHER ${cstr(out.qr_other_door)}\n`;
    h += `#define VEC_QR_IAT ${qrIat}\n#define VEC_QR_EXP ${qrExp}\n`;
    h += 'typedef struct { const char *name; const char *json; int expect; } vec_t;\nstatic const vec_t VECS[] = {\n';
    for (const c of cases) h += `  { ${cstr(c.name)}, ${cstr(c.json)}, ${c.expect ? 1 : 0} },\n`;
    h += '};\n';
    fs.writeFileSync(process.argv[3], h);
}
console.log(`${cases.length} vectors`);
